def _source_part(cp_path,key,change):
    cp=json.loads(cp_path.read_bytes());path=cp_path.parent/cp[key]['path']
    value=json.loads(path.read_bytes());change(value)
    path.write_text(json.dumps(value),encoding='utf8');cp[key]['sha256']=hashlib.sha256(path.read_bytes()).hexdigest()
    cp_path.write_text(json.dumps(cp),encoding='utf8')


