@pytest.mark.parametrize('fault',['forged_flags','missing_source_cp','bad_hash','price99','price_date','price_zero',
    'source_state','result_state','source_metadata','awaiting_promoted','wrong_next'])
def test_reused_markers_cannot_replace_the_exact_native_checkpoint_proof(saved_native,tmp_path,monkeypatch,fault):
    directory,source_cp,_=saved_native;result=read_result(directory)
    if fault=='forged_flags':result['collection_performed']=True
    elif fault=='missing_source_cp':source_cp.unlink()
    elif fault=='bad_hash':(source_cp.parent/'member_prices.json').write_text('{}',encoding='utf8')
    elif fault=='price99':_source_part(source_cp,'prices',lambda value:value['rows'].pop())
    elif fault=='price_date':_source_part(source_cp,'prices',lambda value:value['rows'][0].update(previous_raw_date='2026-11-11'))
    elif fault=='price_zero':_source_part(source_cp,'prices',lambda value:value['rows'][0].update(previous_raw_close=0))
    elif fault=='source_state':_source_part(source_cp,'version_state',lambda value:value['versions']['v2.0'].update(next_holding='long_microcap_short_zz1000'))
    elif fault=='result_state':
        result['versions'][0]['signal']['microcap_mom']=.12345;sync_signals(directory,result)
    elif fault=='source_metadata':
        def missing(value):value.pop('source_manifest_sha256');value.pop('source_files')
        _source_part(source_cp,'period',missing)
        result['period_sha256']=json.loads(source_cp.read_bytes())['period']['sha256']
    elif fault in {'awaiting_promoted','wrong_next'}:
        cp=json.loads(source_cp.read_bytes())
        cp.update(period_status='awaiting_handoff') if fault=='awaiting_promoted' else cp.update(next_trade_date='2026-11-12')
        source_cp.write_text(json.dumps(cp),encoding='utf8')
    # Re-signing a tampered envelope is not permission to skip semantic source
    # checks: even these attacks must retain the original native state/100 basis.
    if source_cp.exists():result['checkpoint_sha256']=hashlib.sha256(source_cp.read_bytes()).hexdigest()
    write_result(directory,result)
    with pytest.raises(ValueError):
        run_main(monkeypatch,directory,tmp_path/'blocked',clock='2026-11-12T16:06:00+08:00',checkpoint=source_cp)
    assert not (tmp_path/'blocked/metadata.json').exists()
